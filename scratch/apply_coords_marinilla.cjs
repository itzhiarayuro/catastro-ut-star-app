async function applyCoords() {
    console.log('--- APLICANDO COORDENADAS EN MARINILLA ---');
    
    let updated = 0;
    let notFound = 0;
    let batch = db.batch();
    let batchCount = 0;

    for (const item of dataToApply) {
        // Intentar con C01AA si CO1AA falla (común error de O vs 0)
        let actualId = item.id;
        if (actualId === 'CO1AA') actualId = 'C01AA'; // Ya sabemos que en DB es C01AA
        
        const docId = `MARINILLA_${actualId}`;
        const docRef = db.collection('fichas').doc(docId);
        const doc = await docRef.get();
        
        if (doc.exists) {
            batch.update(docRef, {
                coordenada_x: item.x,
                coordenada_y: item.y,
                gps: {
                    ...doc.data().gps,
                    lat: item.lat,
                    lng: item.lon
                },
                lastSync: new Date().toISOString()
            });
            console.log(`[QUEUED] ${actualId} updated with Lat: ${item.lat}, Lon: ${item.lon}`);
            updated++;
            batchCount++;
            
            if (batchCount >= 400) {
                await batch.commit();
                batch = db.batch();
                batchCount = 0;
            }
        } else {
            console.warn(`[SKIP] Documento no encontrado: ${docId}`);
            notFound++;
        }
    }

    if (batchCount > 0) {
        await batch.commit();
    }

    console.log(`\n✅ Resumen: ${updated} actualizados, ${notFound} no encontrados.`);
}

applyCoords().catch(console.error);
